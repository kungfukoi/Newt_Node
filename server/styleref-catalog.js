import { createHash } from "node:crypto";

const api = "https://styleref.io/api/v1";
const imageOrigin = "https://piteahvrjstrlirkpoid.supabase.co";
const prefix = "styleref-";
// Curated out of browsing; retain detail access for existing saved Looks/workflows.
const excludedCatalogSlugs = new Set(["9a2adtz6-cd8d77ee2f51"]); // Real Moments
const fail = (message, status = 502, retryAfter = "") => { throw Object.assign(new Error(message), { status, retryAfter }); };
const clean = (value, max = 12000) => typeof value === "string" ? value.trim().slice(0, max) : "";
export function styleRefImageUrl(value) {
  try {
    if(typeof value!=="string"||value.includes("..")||value.includes("\\"))return "";
    const url = new URL(value);
    if (url.origin !== imageOrigin || url.username || url.password || url.search || url.hash) return "";
    if (!/^\/storage\/v1\/object\/public\/images\/[a-z0-9_/-]+\.(?:webp|png|jpe?g|avif)$/i.test(url.pathname) || url.pathname.includes("..")) return "";
    return url.href;
  } catch { return ""; }
}
function image(value, index) {
  const url = styleRefImageUrl(value);
  return url ? { id: `styleref-image-${index}`, url: `/api/style-library/styleref-image?url=${encodeURIComponent(url)}`, fileName: new URL(url).pathname.split("/").pop() } : null;
}
export function normalizeStyleRefCard(record) {
  if (!/^[a-z0-9-]{1,65}$/.test(record?.slug || "") || !clean(record.name)) return null;
  return { id: prefix + record.slug, catalogId: prefix + record.slug, name: clean(record.name,120), category: clean(record.category,80), prompt: "", notes: "", sref: "",
    sourceProvider: "StyleRef", sourceAuthor: clean(record.author,120), sourceAttribution: "Generated by StyleRef.io", sourceUrl: `https://styleref.io/share/${record.slug}`,
    tags: (Array.isArray(record.tags)?record.tags:[]).map(value=>clean(value,80)).filter(Boolean).slice(0,40),
    colours: (Array.isArray(record.palette)?record.palette:[]).filter(hex=>/^#(?:[a-f0-9]{3}|[a-f0-9]{6})$/i.test(hex)).slice(0,6).map(hex=>({name:hex,hex,percent:null})),
    examples: [image(record.heroImage,0)].filter(Boolean), detailAvailable:true };
}
async function boundedBody(response, maximum) {
  if (Number(response.headers.get("content-length")) > maximum) { await response.body?.cancel(); fail("StyleRef returned a file that is too large."); }
  const chunks=[];let length=0;
  for await (const chunk of response.body || []) { length+=chunk.length; if(length>maximum) { fail("StyleRef returned a file that is too large."); } chunks.push(chunk); }
  return Buffer.concat(chunks);
}
export function createStyleRefCatalog({ fetchImpl=fetch, createdStore, searchSharedCompact, cacheMs=300000 }={}) {
  const cache=new Map(), pending=new Map();let retryUntil=0;
  async function request(url, { binary=false }={}) {
    if(Date.now()<retryUntil)fail("StyleRef is rate limited. Wait before refreshing.",429,String(Math.ceil((retryUntil-Date.now())/1000)));
    let response;
    try { response=await fetchImpl(url,{headers:binary?{Accept:"image/webp,image/png,image/jpeg,image/avif"}:{Accept:"application/json,text/markdown","X-StyleRef-Client":"newtnode"},redirect:"error",signal:AbortSignal.timeout(15000)}); }
    catch { fail("Could not connect to StyleRef. Check your connection and retry.",503); }
    if(response.status===429) {
      const raw=response.headers.get("retry-after")||"60", seconds=/^\d+$/.test(raw)?Number(raw):Math.ceil((Date.parse(raw)-Date.now())/1000);
      const wait=Math.max(1,Math.min(3600,Number.isFinite(seconds)?seconds:60));retryUntil=Date.now()+wait*1000;
      await response.body?.cancel();fail(`StyleRef rate limit reached. Retry in ${wait} seconds.`,429,String(wait));
    }
    if(!response.ok) {await response.body?.cancel();fail(response.status===404?"This StyleRef look is no longer public or available.":`StyleRef returned HTTP ${response.status}. Retry later.`,response.status===404?404:502);}
    const type=response.headers.get("content-type")?.split(";")[0].trim()||"";
    if(binary&&!['image/webp','image/png','image/jpeg','image/avif'].includes(type)){await response.body?.cancel();fail("StyleRef did not return a supported image.");}
    if(!binary&&!['application/json','text/markdown','text/plain'].includes(type)){await response.body?.cancel();fail("StyleRef returned a page instead of catalog data.");}
    return {buffer:await boundedBody(response,binary?16*1024*1024:2*1024*1024),type};
  }
  async function cached(key, refresh, action) {
    const previous=cache.get(key);if(!refresh&&previous&&previous.until>Date.now())return previous.value;
    if(pending.has(key))return pending.get(key);
    const work=action().then(value=>{if(cache.size>=60)cache.delete(cache.keys().next().value);cache.set(key,{value,until:Date.now()+cacheMs});return value;}).finally(()=>pending.delete(key));
    pending.set(key,work);return work;
  }
  async function listing(q="",category="",refresh=false) {
    return cached(`list:${q}:${category}`,refresh,async()=>{
      const styles=[];let offset=0,truncated=false;
      while(offset<=200){
        const params=new URLSearchParams({limit:"25",offset:String(offset),sort:"recent"});if(q)params.set("query",q);if(category)params.set("category",category);
        const {buffer}=await request(`${api}/styles?${params}`);let data;try{data=JSON.parse(buffer);}catch{fail("StyleRef returned invalid catalog data.");}
        if(!Array.isArray(data.styles))fail("StyleRef returned an unsupported catalog response.");
        styles.push(...data.styles.filter(record=>!excludedCatalogSlugs.has(record?.slug)).map(normalizeStyleRefCard).filter(Boolean));
        if(!data.hasMore)break;
        const next=Number(data.nextOffset);if(!Number.isInteger(next)||next<=offset)fail("StyleRef returned invalid pagination.");
        if(next>200){truncated=true;break;}offset=next;
      }
      return {styles:[...new Map(styles.map(style=>[style.id,style])).values()],truncated};
    });
  }
  async function search({q="",category="",offset=0,limit=48,refresh=false,own=false}={}) {
    q=clean(q,300);category=clean(category,80);
    const sharedOnly=!own&&category==="Shared";
    const [remoteResult,createdResult]=await Promise.allSettled([sharedOnly?Promise.resolve({all:{styles:[]},matched:{styles:[],truncated:false}}):(async()=>{const all=await listing("","",refresh);return {all,matched:category&&!all.styles.some(style=>style.category===category)?{styles:[],truncated:false}:q||category?await listing(q,category,refresh):all};})(),(async()=>{
      if(own||!createdStore)return {looks:[],shared:false};
      const state=await createdStore.state?.();return {looks:await createdStore.read(),shared:state?.mode==="shared"};
    })()]);
    if(remoteResult.status==="rejected"&&(createdResult.status==="rejected"||!createdResult.value.looks.length))throw remoteResult.reason;
    const {all,matched}=remoteResult.status==="fulfilled"?remoteResult.value:{all:{styles:[]},matched:{styles:[],truncated:false}};
    const created=createdResult.status==="fulfilled"?createdResult.value.looks:[],shared=createdResult.status==="fulfilled"&&createdResult.value.shared;
    const words=q.toLowerCase().split(/\s+/).filter(Boolean);
    const local=created.filter(style=>(sharedOnly?shared:!category||style.category===category||style.tags.includes(category))&&words.every(word=>[style.name,style.prompt,style.category,...style.tags].join(" ").toLowerCase().includes(word)));
    const start=Math.max(0,Math.trunc(Number(offset)||0)),size=Math.min(96,Math.max(1,Math.trunc(Number(limit)||48)));
    let compact,compactError;
    if(sharedOnly&&searchSharedCompact){
      try{compact=await searchSharedCompact({q,offset:Math.max(0,start-local.length),limit:size});}
      catch(error){compactError=error;}
    }
    if(sharedOnly&&!compact&&createdResult.status==="rejected")throw createdResult.reason;
    if(compactError&&!shared)throw compactError;
    const warning=[remoteResult.status==="rejected"?`Online catalog unavailable: ${remoteResult.reason.message}`:"",createdResult.status==="rejected"?`Custom looks unavailable: ${createdResult.reason.message}`:"",compactError?`Shared catalog unavailable: ${compactError.message}`:""].filter(Boolean).join(" ");
    const styles=[...local,...matched.styles].slice(start,start+size);
    if(compact)styles.push(...compact.styles.slice(0,size-styles.length));
    return {ready:true,source:"styleref",sourceLabel:"StyleRef",sourceUrl:"https://styleref.io",attribution:"StyleRef.io",populating:false,truncated:matched.truncated,warning,
      indexed:all.styles.length+created.length+(compact?.indexed??0),remoteCount:all.styles.length,localCount:created.length,sharedCount:(shared?created.length:0)+(compact?.indexed??0),total:local.length+matched.styles.length+(compact?.total??0),offset:start,limit:size,categories:[...new Set([...(own?[]:["Shared"]),...(sharedOnly?cache.get("list::")?.value.styles||[]:all.styles).concat(created).map(style=>style.category).filter(Boolean)])].sort(),styles};
  }
  async function detail(id) {
    if(!id?.startsWith(prefix)){
      if(!/^[a-z0-9-]{1,80}$/.test(id||""))fail("Choose a valid catalog look.",400);
      const created=createdStore?(createdStore.get?await createdStore.get(id):(await createdStore.read()).find(style=>style.id===id)):null;
      if(created)return {style:created};
      fail("This look is not available in the StyleRef catalog. Saved looks remain available in your personal catalogs.",404);
    }
    const slug=id.slice(prefix.length);if(!/^[a-z0-9-]{1,65}$/.test(slug))fail("Choose a valid StyleRef look.",400);
    return cached(`detail:${slug}`,false,async()=>{
      const all=await listing();let card=all.styles.find(style=>style.id===id);
      // A saved public look may no longer appear in the first 225 gallery entries.
      const {buffer}=await request(`${api}/styles/${slug}?format=json`);let data;try{data=JSON.parse(buffer);}catch{fail("StyleRef returned invalid look details.");}
      if(!data||typeof data.name!=="string"||!data.sections||typeof data.sections!=="object")fail("StyleRef returned incomplete look details.");
      card ||= normalizeStyleRefCard({slug,name:data.name});
      const compiled=await request(`${api}/styles/${slug}?format=flux&compact=1&raw=1`);
      const prompt=compiled.buffer.toString("utf8").replace(/^\s*\[YOUR SUBJECT\/SCENE PROMPT HERE\]\.\s*/i,"").trim();
      if(!prompt||prompt.length>12000)fail("StyleRef's visual specification could not be imported intact.");
      const references=(Array.isArray(data.referenceImages)?data.referenceImages:[]).map((item,index)=>image(item.url,index)).filter(Boolean);
      const seen=new Set();const examples=references.filter(item=>{if(seen.has(item.url))return false;seen.add(item.url);return true;}).slice(0,8);
      return {style:{...card,name:clean(data.name,120),notes:clean(data.description,4000),prompt,examples:examples.length?examples:card.examples,similarStyles:[],sourceSpecificationHash:createHash("sha256").update(prompt).digest("hex")}};
    });
  }
  async function asset(value) {
    const url=styleRefImageUrl(value);if(!url)fail("Choose a valid StyleRef catalog image.",400);
    // Only fixed, public StyleRef image storage is reachable; redirects and arbitrary hosts are rejected.
    return request(url,{binary:true});
  }
  return {search,detail,asset};
}

export function registerStyleRefCatalogRoutes(app, options={}) {
  const catalog=createStyleRefCatalog(options);
  const error=(res,e,fallback)=>{if(e.retryAfter)res.set("Retry-After",e.retryAfter);res.status(e.status||500).json({error:e.status?e.message:fallback});};
  app.get("/api/style-library/catalog",async(req,res)=>{try{res.json(await catalog.search({...req.query,refresh:req.query.refresh==="1",own:req.query.own==="1"}));}catch(e){error(res,e,"Could not read StyleRef. Check your connection and retry.");}});
  app.get("/api/style-library/catalog/:id",async(req,res)=>{try{res.json(await catalog.detail(req.params.id));}catch(e){error(res,e,"Could not read this StyleRef look.");}});
  app.get("/api/style-library/styleref-image",async(req,res)=>{try{const value=await catalog.asset(req.query.url);res.set({"Content-Type":value.type,"Cache-Control":"private, max-age=300","X-Content-Type-Options":"nosniff"}).send(value.buffer);}catch(e){error(res,e,"Could not load this StyleRef example.");}});
}
