import { test, expect } from "@playwright/test";
import { openFixture, wireAttachmentErrors } from "./helpers.mjs";

test("project controls share the left toolbar and reclaim the canvas menu row", async ({ page }, testInfo) => {
  const { errors, fixture } = await openFixture(page, { count: 271, scale: .3, uiState: { nodePaletteCollapsed: false, nodeMenuCollapsed: true } });
  const controls = page.getByRole("toolbar", { name: "Project controls" });
  const layout = await page.evaluate(() => {
    const toolbar = document.querySelector(".node-toolbar").getBoundingClientRect();
    const controls = document.querySelector(".canvas-menu-bar").getBoundingClientRect();
    const canvas = document.querySelector(".node-canvas").getBoundingClientRect();
    const recent = document.querySelector('[data-menu-trigger="recent"]').getBoundingClientRect();
    const title = document.querySelector('.canvas-document-name').getBoundingClientRect();
    const file = document.querySelector('[data-menu-trigger="file"]').getBoundingClientRect();
    const add = document.querySelector('.canvas-quick-new').getBoundingClientRect();
    const save = document.querySelector('[aria-label="Save project"]').getBoundingClientRect();
    return { aligned: Math.abs(toolbar.top - canvas.top), left: controls.right < canvas.left, stacked: recent.bottom < title.top, fileBetween: recent.right <= file.left && file.right <= save.left && save.right <= add.left, inside: controls.left >= toolbar.left && controls.right <= toolbar.right };
  });
  expect(layout.aligned).toBeLessThan(2); expect(layout.left).toBe(true); expect(layout.stacked).toBe(true); expect(layout.inside).toBe(true);
  expect(layout.fileBetween).toBe(true);
  const name = controls.getByRole("textbox", { name: "Workflow name" });
  await name.fill("Draft name");
  await name.press("Enter");
  await name.fill("Cancel this edit");
  await name.press("Escape");
  await expect(name).toHaveValue("Draft name");
  await expect(page.getByRole("button", { name: /menu bar/ })).toHaveCount(0);
  await controls.getByRole("button", { name: "File", exact: true }).focus();
  await page.keyboard.press("ArrowDown");
  await expect(page.getByRole("menuitem", { name: "New canvas", exact: true })).toBeFocused();
  await page.keyboard.press("End");
  await expect(page.getByRole("menuitem", { name: "Import workflow…" })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(controls.getByRole("button", { name: "File", exact: true })).toBeFocused();
  await controls.getByRole("button", { name: "File", exact: true }).click();
  await page.getByRole("menuitem", { name: "Rename…" }).click();
  await expect(name).toBeFocused();
  await name.fill("Pepsi_Create_Footage");
  await page.keyboard.press("Enter");
  await expect(name).toHaveValue("Pepsi_Create_Footage");
  await controls.getByRole("button", { name: "Recent Projects" }).click();
  await expect(page.getByRole("menu", { name: "Recent Projects" })).toContainText("No recent projects");
  await page.screenshot({ path: testInfo.outputPath("left-toolbar-recent.png") });
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Hide node palette", exact: true }).click();
  await expect(controls).toBeHidden();
  await page.locator(".node-canvas").getByRole("button", { name: "Show node palette", exact: true }).click();
  await expect(controls).toBeVisible();
  await expect(page.getByRole("menu", { name: "Recent Projects" })).toHaveCount(0);
  expect((await wireAttachmentErrors(page, fixture.edges)).every(item => !item.missing && item.start < 2 && item.end < 2)).toBe(true);
  const saved = page.waitForRequest(request => request.url().endsWith("/api/saved-workflows") && request.method() === "POST");
  await controls.getByRole("button", { name: "Save project", exact: true }).click();
  expect((await saved).postDataJSON().name).toBe("Pepsi_Create_Footage");
  await page.screenshot({ path: testInfo.outputPath("left-toolbar-desktop.png") });
  await page.setViewportSize({ width: 375, height: 812 });
  await controls.getByRole("button", { name: "File", exact: true }).click();
  await expect(page.getByRole("menuitem", { name: "Save As…" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("left-toolbar-mobile.png") });
  expect(errors).toEqual([]);
});

