test("Named local collections, bulk selection and save destinations persist independently", async ({ page }) => {
  const { errors } = await openFixture(page, { fixture: { nodes: [], edges: [], groups: [], viewport: { x: 0, y: 0, scale: 1 } }, uiState: { lookbookCollectionRows: 4 } });
  let library = { revision: 0, collections: [{ id: "first", name: "First", styles: [] }, { id: "second", name: "Second", styles: [] }] }, conflict = false;
  const looks = ["Ink", "Wash"].map(name => ({ id: name.toLowerCase(), name, sourceUrl: `https://catalog.example/library/${name.toLowerCase()}`, examples: [{ id: "one", localUrl: "/outputs/e2e/example.png" }], prompt: "Paper and ink", styleAnalysis: { stylePrompt: "Fine ink contours on warm textured paper" } }));
  const json = (route, data) => route.fulfill({ contentType: "application/json", body: JSON.stringify(data) });
  await page.route("**/api/style-library", route => {
    if (route.request().method() === "PUT") {
      if (conflict) return route.fulfill({ status: 409, contentType: "application/json", body: JSON.stringify({ error: "Collection changed; retry" }) });
      library = { ...route.request().postDataJSON(), revision: library.revision + 1 };
    }
    return json(route, library);
  });
  await page.route("**/api/style-library/catalog?**", route => json(route, { ready: true, indexed: 2, total: 2, categories: [], styles: looks }));
  await page.route("**/api/style-library/catalog/**", route => json(route, { style: looks.find(look => route.request().url().endsWith(look.id)) }));
  await page.getByRole("button", { name: "Looks", exact: true }).click();
  const choose = async (label, name, root = page) => { await root.getByRole("combobox", { name: label, exact: true }).click(); await root.getByRole("option", { name, exact: true }).click(); };
  await page.getByRole("combobox", { name: "Looks source", exact: true }).click();
  await expect(page.getByRole("option", { name: "Commercial", exact: true })).toBeVisible();
  await expect(page.getByRole("option", { name: "Starred", exact: true })).toBeVisible();
  await expect(page.getByRole("option", { name: "First", exact: true })).toBeVisible();
  await expect(page.getByRole("option", { name: "My collection", exact: true })).toHaveCount(0);
  await page.getByRole("combobox", { name: "Looks source", exact: true }).press("Escape");
  await page.getByRole("button", { name: "New Catalog", exact: true }).click();
  await page.getByLabel("Catalog name", { exact: true }).fill("Starred");
  await page.getByRole("button", { name: "Create Catalog", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "already in use" })).toBeVisible();
  await page.getByLabel("Catalog name", { exact: true }).fill("Cinema references");
  await page.getByRole("button", { name: "Create Catalog", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Looks source", exact: true })).toHaveText("Cinema references");
  await expect(page.getByRole("combobox", { name: "Collection", exact: true })).toHaveCount(0);
  await choose("Looks source", "Commercial");
  await page.getByRole("checkbox", { name: "Select Ink", exact: true }).check(); await page.getByRole("checkbox", { name: "Select Wash", exact: true }).check();
  await choose("Add to collection destination", "Second");
  await page.screenshot({ path: test.info().outputPath("lookbook-collections.png"), fullPage: true });
  await expect(page.getByRole("checkbox", { name: "Select Ink", exact: true })).toBeChecked();
  conflict = true; await page.getByRole("button", { name: "Add to collection", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Collection changed" })).toBeVisible();
  await expect(page.getByRole("checkbox", { name: "Select Ink", exact: true })).toBeChecked();
  conflict = false; await page.getByRole("button", { name: "Add to collection", exact: true }).click();
  await expect(page.getByRole("checkbox", { name: "Select Ink", exact: true })).not.toBeChecked();
  expect(library.collections.find(item => item.id === "second").styles).toHaveLength(2);
  await expect(page.getByRole("button",{name:"Star look: Ink",exact:true})).toHaveAttribute("aria-pressed","false");
  await choose("Looks source", "Starred");
  await expect(page.getByRole("button",{name:"View Ink",exact:true})).toHaveCount(0);
  await choose("Looks source", "Commercial");
  await page.getByRole("button", { name: "View Ink", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Style details", exact: true });
  await expect(dialog.getByText("Manage collections", { exact: true })).toHaveCount(0);
  await expect(dialog.getByRole("combobox", { name: "Save destination", exact: true })).toHaveText("Second");
  await choose("Save destination", "First", dialog);
  await dialog.getByRole("button", { name: "Save to my collection", exact: true }).click();
  expect(library.collections.find(item => item.id === "first").styles).toHaveLength(1);
  expect(library.collections.find(item => item.id === "second").styles).toHaveLength(2);
  await choose("Save destination", "Cinema references", dialog);
  await dialog.getByRole("button", { name: "Close style details", exact: true }).click();
  await page.getByRole("button", { name: "View Wash", exact: true }).click();
  await expect(dialog.getByRole("combobox", { name: "Save destination", exact: true })).toHaveText("Cinema references");
  await dialog.getByRole("button", { name: "Save to my collection", exact: true }).click();
  await dialog.getByRole("button", { name: "Close style details", exact: true }).click();
  await page.reload(); await page.getByRole("button", { name: "Looks", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Add to collection destination", exact: true })).toHaveText("Cinema references");
  await choose("Looks source", "Cinema references");
  await expect(page.getByRole("button", { name: "View Wash", exact: true })).toBeVisible(); await expect(page.getByRole("button", { name: "View Ink", exact: true })).toHaveCount(0);
  await choose("Looks source", "Second");
  await expect(page.getByRole("button", { name: "View Ink", exact: true })).toBeVisible();
  const strip=page.getByLabel("Style previews",{exact:true});
  await expect(strip).toHaveCount(1);
  const rowTops=()=>strip.locator(".stylebuilder-tile").evaluateAll(nodes=>[...new Set(nodes.map(node=>Math.round(node.getBoundingClientRect().top)))]);
  expect(await rowTops()).toHaveLength(1);
  const secondHandle=page.getByRole("separator",{name:"Resize Second rows",exact:true});
  await secondHandle.press("ArrowDown");await expect(secondHandle).toHaveAttribute("aria-valuenow","2");
  expect(await rowTops()).toHaveLength(2);
  await choose("Looks source","First");
  await expect(page.getByRole("separator",{name:"Resize First rows",exact:true})).toHaveAttribute("aria-valuenow","1");
  await choose("Looks source","Second");await expect(secondHandle).toHaveAttribute("aria-valuenow","2");
  await expect(strip).toHaveCount(1);await expect(strip.locator(".stylebuilder-tile")).toHaveCount(2);
  await page.reload();await page.getByRole("button",{name:"Looks",exact:true}).click();
  await choose("Looks source","Second");await expect(secondHandle).toHaveAttribute("aria-valuenow","2");
  await choose("Looks source","First");await expect(page.getByRole("separator",{name:"Resize First rows",exact:true})).toHaveAttribute("aria-valuenow","1");
  await expect(page.getByRole("combobox", { name: "Add to collection destination", exact: true })).toHaveText("Cinema references");
  await choose("Looks source","Cinema references");
  await page.getByRole("button",{name:"Delete Catalog",exact:true}).click();
  await page.getByRole("button",{name:"Cancel",exact:true}).click();
  expect(library.collections.some(item=>item.name==="Cinema references")).toBe(true);
  await page.getByRole("button",{name:"Delete Catalog",exact:true}).click();
  conflict=true;
  await page.getByRole("button",{name:"Confirm delete",exact:true}).click();
  await expect(page.getByRole("alert").filter({ hasText: "Collection changed" })).toBeVisible();
  expect(library.collections.some(item=>item.name==="Cinema references")).toBe(true);
  conflict=false;
  await page.getByRole("button",{name:"Confirm delete",exact:true}).click();
  await expect(page.getByRole("combobox",{name:"Looks source",exact:true})).toHaveText("Starred");
  await expect(page.getByRole("combobox",{name:"Add to collection destination",exact:true})).toHaveText("Starred");
  expect(library.collections.some(item=>item.name==="Cinema references")).toBe(false);
  expect(library.collections.find(item=>item.id==="second").styles).toHaveLength(2);
  await expect(page.getByRole("button",{name:"Delete Catalog",exact:true})).toHaveCount(0);
  await page.reload();await page.getByRole("button",{name:"Looks",exact:true}).click();
  await page.getByRole("combobox",{name:"Looks source",exact:true}).click();
  await expect(page.getByRole("option",{name:"Cinema references",exact:true})).toHaveCount(0);
  await page.getByRole("combobox",{name:"Looks source",exact:true}).press("Escape");
  await expect(page.getByRole("button",{name:"Delete Catalog",exact:true})).toHaveCount(0);
  expect(errors).toEqual([]);
});
